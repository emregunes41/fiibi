export function getPalette(id) {
  return PALETTES[id] || PALETTES.dark;
}

export function getPaletteList() {
  return Object.entries(PALETTES).map(([id, p]) => ({ id, ...p }));
}

export function getDarkPalettes() {
  return getPaletteList().filter(p => p.isDark);
}

export function getLightPalettes() {
  return getPaletteList().filter(p => !p.isDark);
}
